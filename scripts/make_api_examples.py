"""Write docs/API_EXAMPLES.md from REAL responses of a running API (nothing is hand-written).

    python scripts/run_api.py &            # in another terminal
    python scripts/make_api_examples.py [--url http://localhost:8000]
Uses the committed 20-cell sample (SIMULATED data). Long lists are shortened with '...'.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import httpx
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.config import get_config  # noqa: E402


def shorten(o, n=2):
    if isinstance(o, list):
        return [shorten(x, n) for x in o[:n]] + ([f"... (+{len(o) - n} more)"] if len(o) > n else [])
    if isinstance(o, dict):
        return {k: shorten(v, n) for k, v in o.items()}
    return o


def block(o) -> str:
    return "```json\n" + json.dumps(o, indent=2) + "\n```\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--url", default="http://localhost:8000")
    a = ap.parse_args()
    cfg = get_config()
    key = {}
    c = httpx.Client(base_url=a.url, timeout=60, headers=key)
    if c.get("/health").status_code != 200:
        sys.exit(f"API at {a.url} is not healthy; start it with: python scripts/run_api.py")
    s = pd.read_csv(ROOT / cfg["paths"]["sample_dir"] / cfg["sample"]["filename"], parse_dates=["timestamp"]).drop(columns=["data_source"])
    T = pd.Timestamp("2026-02-25 20:00")
    win = s[(s.timestamp <= T) & (s.timestamp > T - pd.Timedelta(minutes=5 * 80))]
    one = json.loads(win[win.site_id == "CELL_006"].to_json(orient="records", date_format="iso"))
    many = json.loads(win.to_json(orient="records", date_format="iso"))
    L = ["# API examples (real responses)", "",
         "> Generated by `scripts/make_api_examples.py` from a running server on the SIMULATED 20-cell sample. "
         "Interactive docs: `http://localhost:8000/docs`. Long lists are shortened.", "",
         "Every request needs **at least N consecutive 5-minute readings per cell** (N is `history_required_steps` from `/model/info`; "
         "73 for the hybrid). Send `null` for a failed sensor value, never an impossible number.", ""]

    def section(title, curl, resp, note=""):
        L.extend([f"## {title}", "", f"```bash\n{curl}\n```", "", note + ("\n" if note else ""), f"Response (HTTP {resp.status_code}):", ""])
        try:
            L.append(block(shorten(resp.json())))
        except ValueError:
            L.append("```\n" + resp.text[:600] + "\n```\n")

    section("GET /health", "curl localhost:8000/health", c.get("/health"))
    info = c.get("/model/info")
    section("GET /model/info", "curl localhost:8000/model/info", info, "`test_metrics` come from the held-out test period of the simulated dataset.")
    first = {k: v for k, v in one[0].items()}
    L += ["## POST /predict  (one cell, stateless)", "",
          "```bash\ncurl -X POST 'localhost:8000/predict?raise_alerts=false' -H 'Content-Type: application/json' -d @request.json\n```", "",
          f"`request.json` = `{{\"readings\": [ ... {len(one)} readings, oldest to newest ... ]}}`. One reading:", "", block(first)]
    r = c.post("/predict?raise_alerts=false", json={"readings": one})
    L += [f"Response (HTTP {r.status_code}):", "", block(r.json())]
    r = c.post("/predict/batch?raise_alerts=false", json={"readings": many})
    b = r.json()
    L += ["## POST /predict/batch  (every cell in one call)", "",
          f"```bash\ncurl -X POST 'localhost:8000/predict/batch?raise_alerts=false' -H 'Content-Type: application/json' -d @all_cells.json\n```", "",
          f"{len(many)} readings from {win.site_id.nunique()} cells. Response (HTTP {r.status_code}), showing 2 of {len(b['results'])} results and the per-cell error map:", "",
          block({"results": [shorten(x) for x in b["results"][:2]], "errors": b["errors"]})]
    stream = c.post("/readings", json={"readings": one[:3], "predict": False})
    section("POST /readings  (streaming mode, buffer only)", "curl -X POST localhost:8000/readings -H 'Content-Type: application/json' -d '{\"readings\": [...], \"predict\": false}'", stream,
            "With `predict: true` (the default) the service predicts as soon as the buffer holds enough history and raises alerts.")
    section("GET /alerts", "curl 'localhost:8000/alerts?limit=2&min_severity=WARNING'", c.get("/alerts?limit=2&min_severity=WARNING"))
    sites = c.get("/sites")
    L += ["## GET /sites", "", "```bash\ncurl localhost:8000/sites\n```", "", f"Response (HTTP {sites.status_code}), 2 of {len(sites.json())} sites:", "", block(shorten(sites.json(), 2))]
    sid = next((x["site_id"] for x in sites.json() if x["buffered_readings"]), "CELL_006")
    section("GET /sites/{site_id}/history", f"curl 'localhost:8000/sites/{sid}/history?limit=2'", c.get(f"/sites/{sid}/history?limit=2"))
    m = c.get("/metrics")
    section("GET /metrics", "curl localhost:8000/metrics   # or ?format=prometheus", m)
    bad = [dict(x) for x in one]; bad[3]["latency_ms"] = -5.0
    section("Error: impossible value (422)", "curl -X POST localhost:8000/predict -d '{... \"latency_ms\": -5 ...}'", c.post("/predict", json={"readings": bad}),
            "The offending value is not echoed back; the field path tells you which reading to fix.")
    section("Error: not enough history (422)", "curl -X POST localhost:8000/predict -d '{\"readings\": [ ...10 readings... ]}'", c.post("/predict", json={"readings": one[:10]}))
    section("Error: unknown route (404)", "curl localhost:8000/nope", c.get("/nope"))
    out = ROOT / "docs" / "API_EXAMPLES.md"
    out.write_text("\n".join(L), encoding="utf-8")
    print(f"Wrote {out} ({len(L)} blocks)")


if __name__ == "__main__":
    main()
